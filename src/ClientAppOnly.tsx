import dynamic from 'next/dynamic';

/**
 * SPA-дашборд, отключённый от серверного рендера.
 *
 * Зачем: раньше все маршруты дашборда обслуживал catch-all `pages/[...slug].tsx`,
 * который Next рендерил только по запросу. После распила на явные страницы
 * (это было необходимо, чтобы рядом заработал App Router лендинга) страницы
 * стали пререндериться на этапе сборки — и код, читающий `window` в теле
 * рендера (например, OAuth-колбэки дашборда), начал падать с
 * `ReferenceError: window is not defined`.
 *
 * ssr: false возвращает прежнее поведение и корректен по существу: дашборд
 * живёт за авторизацией, индексировать его не нужно, а серверный проход
 * лишь дублировал бы работу. Логику дашборда при этом менять не пришлось.
 */
const ClientApp = dynamic(() => import('./ClientRoot'), { ssr: false });

export default ClientApp;
