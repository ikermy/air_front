/**
 * Переход из SPA-дашборда на главную страницу.
 *
 * Зачем отдельный хелпер вместо `navigate('/')` из react-router:
 * лендинг после миграции живёт в App Router (`app/[locale]/page.tsx`),
 * а дашборд остался в Pages Router на react-router. Это два разных
 * приложения, и клиентская навигация react-router границу между ними
 * не пересекает — она бы отрисовала СТАРЫЙ `src/Home.jsx` внутри SPA,
 * подменив URL на `/`, но так и не загрузив новый лендинг.
 *
 * Поэтому выход на главную должен быть полноценной загрузкой документа.
 * Побочный эффект полезен: SPA-состояние дашборда сбрасывается целиком,
 * что после логаута как раз и требуется.
 */

/** Режим модального окна авторизации, которое нужно открыть на лендинге. */
export type LandingAuthMode = 'login' | 'register' | 'restore';

/**
 * @param authMode если указан, лендинг откроет модалку авторизации.
 *        Состояние передаётся через query-параметр `?auth=`, потому что
 *        общего клиентского состояния у двух роутеров нет. Лендинг сам
 *        уберёт параметр из адреса после открытия окна.
 */
export function goToLanding(authMode?: LandingAuthMode): void {
  if (typeof window === 'undefined') return;
  window.location.assign(authMode ? `/?auth=${authMode}` : '/');
}
